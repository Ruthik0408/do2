package itsdc.dolphin.do2.xml;


public class ZipWiseReport {

    private String zipFileName;

    private String summaryPdf;

    private String topSheetPdf;

	public String getZipFileName() {
		return zipFileName;
	}

	public void setZipFileName(String zipFileName) {
		this.zipFileName = zipFileName;
	}

	public String getSummaryPdf() {
		return summaryPdf;
	}

	public void setSummaryPdf(String summaryPdf) {
		this.summaryPdf = summaryPdf;
	}

	public String getTopSheetPdf() {
		return topSheetPdf;
	}

	public void setTopSheetPdf(String topSheetPdf) {
		this.topSheetPdf = topSheetPdf;
	}
    
    

}
